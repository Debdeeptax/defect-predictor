"""Train, evaluate and register defect-prediction models.

Examples
--------
python scripts/train.py                       # both levels, 5x5 CV, save + activate best
python scripts/train.py --level function      # one level
python scripts/train.py --quick               # 3x1 CV smoke run, no save
python scripts/train.py --csv my.csv --level class   # train on an uploaded CSV
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.ml.features import LEVELS  # noqa: E402
from app.ml.trainer import METRICS, Trainer, TrainingResult  # noqa: E402

RESULTS_DIR = ROOT / "docs" / "results"


def fmt(row, m: str) -> str:
    return f"{row[f'{m}_mean']:.3f} ± {row[f'{m}_std']:.3f}"


def write_results_md(results: list[TrainingResult]) -> Path:
    lines = ["# Model training results", "",
             "Generated by `scripts/train.py`. Metrics are mean ± std over repeated "
             "stratified k-fold CV (threshold 0.5 for label metrics).", ""]
    for r in results:
        meta = r.metadata
        clean = json.loads((RESULTS_DIR / r.level / "cleaning.json").read_text())
        lines += [f"## {r.level.capitalize()}-level model", "",
                  f"- Dataset: `{meta.get('dataset', '?')}` — {clean['rows_out']} rows after "
                  f"cleaning ({clean['rows_in']} raw; dropped {clean['dropped_na']} NA, "
                  f"{clean['dropped_invalid']} invalid, {clean['dropped_duplicates']} exact duplicates, "
                  f"{clean['dropped_conflicts']} conflicting-label duplicates)",
                  *[f"- Skipped file `{s['file']}`: {s['reason']}" for s in clean["skipped_files"]],
                  *[f"- Excluded release `{p['project']}` ({p['rows']} rows, "
                    f"{p['defect_rate']:.1%} defective — implausible labelling)"
                    for p in clean["dropped_projects"]],
                  f"- Defective rate: {clean['positive_rate']:.1%}; projects: {len(clean['projects'])}",
                  f"- CV: {meta.get('cv', {}).get('folds')} folds × "
                  f"{meta.get('cv', {}).get('repeats')} repeats",
                  f"- **Selected: {meta.get('display_name', r.best_key)}** → "
                  f"`models/{meta.get('file', '-')}`", "",
                  "| Model | " + " | ".join(METRICS) + " |",
                  "|---|" + "---|" * len(METRICS)]
        for key, row in r.summary.iterrows():
            name = f"**{key}**" if key == r.best_key else key
            lines.append(f"| {name} | " + " | ".join(fmt(row, m) for m in METRICS) + " |")
        st = r.stats
        lines += ["", f"**Significance ({st['metric']}, {st['n_folds']} paired folds)**", ""]
        if "friedman" in st:
            lines.append(f"- Friedman χ² = {st['friedman']['chi2']:.2f}, "
                         f"p = {st['friedman']['p']:.2e}")
        lines += ["", "| Best vs | p (Holm) | Cliff's δ | Effect | Significant |",
                  "|---|---|---|---|---|"]
        for p in st["pairwise"]:
            lines.append(f"| {p['vs']} | {p['p_holm']:.2e} | {p['cliffs_delta']:+.3f} | "
                         f"{p['effect']} | {'yes' if p['significant'] else 'no'} |")
        lines += ["", f"_{st['note']}_", ""]
        if not r.lopo.empty:
            lines += ["**Cross-project validation (leave-one-project-out, selected model)**", "",
                      "| Held-out project | n | defect rate | ROC-AUC | F1 | Recall |",
                      "|---|---|---|---|---|---|"]
            for _, row in r.lopo.iterrows():
                lines.append(f"| {row['test_project']} | {row['n']} | {row['defect_rate']:.1%} | "
                             f"{row['roc_auc']:.3f} | {row['f1']:.3f} | {row['recall']:.3f} |")
            lines += [f"| **mean** | | | **{r.lopo['roc_auc'].mean():.3f}** | "
                      f"{r.lopo['f1'].mean():.3f} | {r.lopo['recall'].mean():.3f} |", ""]
        imp = meta.get("feature_importance", [])[:8]
        if imp:
            lines += ["**Top features (permutation importance, Δ ROC-AUC on 25 % hold-out)**", ""]
            lines += [f"{i}. {d['label']} — {d['importance']:.4f}" for i, d in enumerate(imp, 1)]
            lines.append("")
        lines += [f"![ROC]({r.level}/roc_curves.png) "
                  f"![Comparison]({r.level}/model_comparison.png) "
                  f"![Importance]({r.level}/feature_importance.png)", ""]
    out = RESULTS_DIR / "RESULTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--level", choices=[*LEVELS, "all"], default="all")
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--repeats", type=int, default=5)
    ap.add_argument("--csv", type=Path, help="train on this CSV instead of data/raw")
    ap.add_argument("--quick", action="store_true", help="3-fold x1 smoke run, no save")
    ap.add_argument("--no-activate", action="store_true", help="save but keep current active model")
    ap.add_argument("--jobs", type=int, default=-1)
    args = ap.parse_args()

    logging.basicConfig(level=logging.WARNING, format="%(levelname)s %(name)s: %(message)s")
    if args.quick:
        args.folds, args.repeats = 3, 1

    levels = list(LEVELS) if args.level == "all" else [args.level]
    results = []
    for level in levels:
        trainer = Trainer(level, model_dir=ROOT / "models", results_dir=RESULTS_DIR,
                          folds=args.folds, repeats=args.repeats, n_jobs=args.jobs,
                          progress=lambda m: print(m, flush=True))
        results.append(trainer.run(raw_dir=ROOT / "data" / "raw", csv_path=args.csv,
                                   save=not args.quick, activate=not args.no_activate))
    if not args.quick:
        print(f"Wrote {write_results_md(results).relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
